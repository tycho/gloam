//! Rust loader generator.
//!
//! Emits a self-contained crate — `Cargo.toml`, an `#![no_std]` `lib.rs`, and
//! one module per resolved spec (`src/gl.rs`, `src/egl.rs`, `src/vk.rs`,
//! `src/wgl.rs`, `src/glx.rs` — mirroring the C backend's per-spec `.c`/`.h`
//! files in a shared tree).  Every spec family the C backend generates is
//! covered.
//!
//! This module owns the crate-level orchestration: `generate()` dispatches
//! each feature set to its spec's emitter and assembles the crate scaffolding.
//! The pieces live in:
//!
//! - [`abi`] — the ABI scalar map and `TypeRef` → Rust type printers, plus
//!   the derived base-type emitter (shared by every spec).
//! - [`common`] — spec-agnostic table/dispatch emission (name blob, PFN
//!   ranges, XXH3 extension tables, dispatch methods, presence queries).
//! - [`gl_loader`] / [`egl_loader`] / [`vk_loader`] / [`wgl_loader`] /
//!   [`glx_loader`] — per-spec load flows, each mirroring its C
//!   counterpart's contract.
//! - [`vk_types`] — the Vulkan type printer (structs, unions, handles,
//!   enum groups) over the structured registry payloads.
//!
//! Generated-output conventions shared by every module: hand-formatted tables
//! carry `#[rustfmt::skip]`; unsafe operations sit in explicit `unsafe {}`
//! blocks (`#![deny(unsafe_op_in_unsafe_fn)]`), so the output is valid under
//! any edition — the pinned `edition = 2021` is a stable default, not
//! load-bearing.

